// Initialize some initial cards with various states (due today, learning, review)
export function createInitialCards(vocabList: VocabItem[]): Card[] {
  const now = new Date();
  const pastHour = new Date(now.getTime() - 1000 * 60 * 30); // 30 mins ago -> due now
  const yesterday = new Date(now.getTime() - 1000 * 60 * 60 * 24);
  const futureTwoDays = new Date(now.getTime() + 1000 * 60 * 60 * 48);

  return vocabList.map((item, idx) => {
    // Make 4 cards due immediately, 4 in review due soon, and 4 new
    if (idx < 4) {
      return {
        id: `card_${item.id}_en_vi`,
        vocabItemId: item.id,
        template: 'en_vi',
        state: 'review',
        dueAt: pastHour.toISOString(), // DUE NOW
        lastReviewedAt: yesterday.toISOString(),
        stability: 2.8,
        difficulty: 4.5,
        elapsedDays: 1,
        scheduledDays: 1,
        reps: 2,
        lapses: 0,
        version: 2,
      };
    } else if (idx < 8) {
      return {
        id: `card_${item.id}_en_vi`,
        vocabItemId: item.id,
        template: 'en_vi',
        state: 'learning',
        dueAt: pastHour.toISOString(), // DUE NOW
        lastReviewedAt: pastHour.toISOString(),
        stability: 1.2,
        difficulty: 5.2,
        elapsedDays: 0,
        scheduledDays: 0,
        reps: 1,
        lapses: 1,
        version: 1,
      };
    } else {
      return {
        id: `card_${item.id}_en_vi`,
        vocabItemId: item.id,
        template: 'en_vi',
        state: 'new',
        dueAt: now.toISOString(), // NEW CARD
        stability: 0,
        difficulty: 0,
        elapsedDays: 0,
        scheduledDays: 0,
        reps: 0,
        lapses: 0,
        version: 0,
      };
    }
  });
}
